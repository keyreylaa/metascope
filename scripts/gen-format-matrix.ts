import { mkdir, rm } from "node:fs/promises";
import { join, resolve } from "node:path";
import { closeExifTool } from "../src/core/exiftool.js";
import { prepareOutput } from "../src/core/fileOps.js";
import { loadSharp } from "../src/core/sharpLoader.js";
import { readFileGrouped } from "../src/core/reader.js";
import { stripFile } from "../src/core/strip.js";
import { applyTags } from "../src/core/write.js";

interface Row {
  format: string;
  detection: string;
  read: string;
  write: string;
  strip: string;
  notes: string;
}

const DIR = resolve(join(process.cwd(), "test-tmp", "matrix"));
const OUT = join(DIR, "out");

async function probeGeneratable(
  name: string,
  ext: string,
  make: (target: string) => Promise<void>,
): Promise<Row> {
  const source = join(DIR, `matrix.${ext}`);
  await make(source);
  const notes: string[] = [];
  let read: string;
  try {
    const groups = (await readFileGrouped(source, false)).groups;
    read = Object.keys(groups).length > 0 ? "yes" : "empty";
  } catch (error) {
    read = "no";
    notes.push(`read: ${error instanceof Error ? error.message.slice(0, 80) : String(error)}.`);
  }
  const target = await prepareOutput(source, OUT);
  let write: string;
  try {
    const result = await applyTags(target.output, { Artist: "Matrix Probe" });
    write = result.written.includes("Artist")
      ? "yes"
      : `partial (${result.notWritten
          .map((entry) => entry.reason ?? "?")
          .join("; ")
          .slice(0, 80)})`;
  } catch (error) {
    write = `no (${error instanceof Error ? error.message.slice(0, 60) : "?"})`;
  }
  let strip: string;
  try {
    const result = await stripFile(target.output, { mode: "all", verify: true, yes: true });
    strip =
      result.clean === true ? "clean" : `residuals: ${result.residuals.slice(0, 4).join(", ")}`;
  } catch (error) {
    strip = `no (${error instanceof Error ? error.message.slice(0, 60) : "?"})`;
  }
  return {
    format: name,
    detection: "magic bytes",
    read,
    write,
    strip,
    notes: notes.join(" ") || "verified live",
  };
}

async function main(): Promise<void> {
  await rm(DIR, { recursive: true, force: true });
  await mkdir(OUT, { recursive: true });
  const { sharp, message } = await loadSharp();
  if (!sharp) {
    throw new Error(`Cannot probe formats: ${message}`);
  }
  const paint = (color: { r: number; g: number; b: number }) =>
    sharp({
      create: { width: 32, height: 32, channels: 3, background: color },
    });
  const rows: Row[] = [];
  rows.push(
    await probeGeneratable("JPEG", "jpg", (target) =>
      paint({ r: 200, g: 30, b: 30 })
        .jpeg()
        .toFile(target)
        .then(() => undefined),
    ),
  );
  rows.push(
    await probeGeneratable("PNG", "png", (target) =>
      paint({ r: 30, g: 60, b: 200 })
        .png()
        .toFile(target)
        .then(() => undefined),
    ),
  );
  rows.push(
    await probeGeneratable("WebP", "webp", (target) =>
      paint({ r: 60, g: 60, b: 60 })
        .webp()
        .toFile(target)
        .then(() => undefined),
    ),
  );
  rows.push(
    await probeGeneratable("GIF", "gif", (target) =>
      paint({ r: 90, g: 90, b: 30 })
        .gif()
        .toFile(target)
        .then(() => undefined),
    ),
  );
  rows.push(
    await probeGeneratable("TIFF", "tiff", (target) =>
      paint({ r: 30, g: 90, b: 90 })
        .tiff()
        .toFile(target)
        .then(() => undefined),
    ),
  );
  try {
    rows.push(
      await probeGeneratable("AVIF", "avif", (target) =>
        paint({ r: 120, g: 30, b: 120 })
          .avif()
          .toFile(target)
          .then(() => undefined),
      ),
    );
  } catch (error) {
    rows.push({
      format: "AVIF",
      detection: "magic bytes (ftypavif)",
      read: "untested",
      write: "untested",
      strip: "untested",
      notes: `encoder unavailable here: ${error instanceof Error ? error.message.slice(0, 80) : "?"}`,
    });
  }
  rows.push({
    format: "HEIC/HEIF",
    detection: "magic bytes (ftyphec/mif1)",
    read: "via ExifTool when present",
    write: "untested",
    strip: "untested",
    notes: "NOT verified here: no encoder/fixture on this host.",
  });
  rows.push({
    format: "MP4/MOV",
    detection: "magic bytes (ftypisom/qt)",
    read: "via ExifTool when present",
    write: "untested",
    strip: "untested",
    notes: "NOT verified here: no video fixture on this host.",
  });
  rows.push({
    format: "RAW (CR2/TIFF-based)",
    detection: "TIFF magic / CR marker",
    read: "via ExifTool when present",
    write: "not recommended",
    strip: "not recommended",
    notes: "ExifTool warns stripping RAW can break rendering; never claimed otherwise.",
  });

  const lines = [
    "# Format matrix",
    "",
    "Generated by `scripts/gen-format-matrix.ts` against live fixtures unless noted.",
    "Never pretends a write succeeded: `write`/`strip` cells come from re-reads.",
    "",
    "| Format | Detection | Read | Write | Strip --verify | Notes |",
    "| --- | --- | --- | --- | --- | --- |",
    ...rows.map(
      (row) =>
        `| ${row.format} | ${row.detection} | ${row.read} | ${row.write} | ${row.strip} | ${row.notes} |`,
    ),
    "",
  ];
  const { writeFile } = await import("node:fs/promises");
  await mkdir("docs", { recursive: true });
  await writeFile("docs/FORMAT_MATRIX.md", lines.join("\n"));
  console.log(`Wrote docs/FORMAT_MATRIX.md (${rows.length} rows)`);
  await closeExifTool();
}

void main();
